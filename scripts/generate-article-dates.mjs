#!/usr/bin/env node
/**
 * Write src/data/articleDates.ts: slug → listing date for every article whose
 * <ArticleSchema> omits datePublished, so its Article JSON-LD still gets dates.
 * Does not touch public/sitemap.xml.
 * Run: npm run generate:article-dates
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import { execSync } from "child_process";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");

const blogSource = [
  "src/data/blogPosts.tsx",
  "src/data/popeBlogPosts.ts",
  "src/data/saintOfDayBlogPosts.ts",
  "src/data/catholicFeastDateBlogPosts.ts",
]
  .map((f) => fs.readFileSync(path.join(root, f), "utf8"))
  .join("\n");

const dates = new Map();
for (const m of blogSource.matchAll(/"?slug"?: "([^"]+)"[\s\S]*?"?date"?: "(\d{4}-\d{2}-\d{2})"/g)) {
  dates.set(m[1], m[2]);
}

const needDates = new Set();
(function walk(dir) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(p);
    else if (entry.name.endsWith(".tsx")) {
      for (const m of fs.readFileSync(p, "utf8").matchAll(/<ArticleSchema\b([\s\S]*?)\/>/g)) {
        if (/datePublished/.test(m[1])) continue;
        const slug = m[1].match(/url="https:\/\/guidecatholic\.com\/blog\/([^"/]+)\/?"/)?.[1];
        if (slug) needDates.add(slug);
      }
    }
  }
})(path.join(root, "src"));

const out = Object.fromEntries(
  [...dates].filter(([slug]) => needDates.has(slug)).sort(([a], [b]) => a.localeCompare(b))
);
const missing = [...needDates].filter((s) => !dates.has(s));

// Last real change of each article: the git date of the page component that renders only that URL
// (shared template components are skipped, since their date says nothing about one article).
// A file with uncommitted edits counts as changed today.
const app = fs.readFileSync(path.join(root, "src/App.tsx"), "utf8");
const componentFile = new Map(
  [...app.matchAll(/const (\w+) = lazy\(\(\) => import\("\.\/(pages\/[^"]+)"\)\)/g)].map((m) => [m[1], `src/${m[2]}.tsx`])
);
const routes = [...app.matchAll(/<Route path="\/blog\/([^"/:]+)\/" element=\{<(\w+) \/>\}/g)].map((m) => [m[1], m[2]]);
const routesPerComponent = new Map();
for (const [, c] of routes) routesPerComponent.set(c, (routesPerComponent.get(c) ?? 0) + 1);
const dirty = new Set(
  execSync("git status --porcelain", { cwd: root, encoding: "utf8" })
    .split("\n")
    .map((l) => l.slice(3).trim())
    .filter(Boolean)
);
const today = new Date().toLocaleDateString("en-CA"); // local YYYY-MM-DD
const updated = {};
for (const [slug, comp] of routes.sort(([a], [b]) => a.localeCompare(b))) {
  const file = componentFile.get(comp);
  if (!file || routesPerComponent.get(comp) !== 1 || !fs.existsSync(path.join(root, file))) continue;
  const date = dirty.has(file)
    ? today
    : execSync(`git log -1 --format=%cs -- "${file}"`, { cwd: root, encoding: "utf8" }).trim();
  if (date) updated[slug] = date;
}

fs.writeFileSync(
  path.join(root, "src/data/articleDates.ts"),
  `// Generated by scripts/generate-article-dates.mjs — do not edit by hand.\n` +
    `export const ARTICLE_DATES: Record<string, string> = ${JSON.stringify(out)};\n` +
    `/** Last real change of each article page (git), used for the visible "Updated" date and dateModified. */\n` +
    `export const ARTICLE_UPDATED: Record<string, string> = ${JSON.stringify(updated)};\n`
);
console.log(`articleDates.ts: ARTICLE_UPDATED for ${Object.keys(updated).length} articles`);
console.log(`articleDates.ts: ${Object.keys(out).length} slugs (${missing.length} without a listing date)`);
if (missing.length) console.log("  no date:", missing.join(", "));
